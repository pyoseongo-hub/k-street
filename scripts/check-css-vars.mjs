// 🎨 **없는 색을 부르고 있지 않나** — CSS 변수 이름을 맞춰 본다.
//
// ─────────────────────────────────────────────────────────────────────────
// 왜 이 검사가 생겼나 (2026-09-15)
// ─────────────────────────────────────────────────────────────────────────
//   `color: var(--muted, #6b6559)` 라고 적힌 곳이 **여덟 군데** 있었다.
//   그런데 **`--muted` 라는 변수는 어디에도 없다.** 우리 이름은 `--text-muted` 다.
//   그래서 그 여덟 곳은 밝은 화면이든 어두운 화면이든 **언제나 `#6b6559`**,
//   즉 어두운 따뜻한 회색으로 그려졌다. 어두운 화면(바탕 #131316)에서는
//   거의 검정 위의 검정이라 **읽을 수가 없다.**
//
//   🚨 더 나쁜 것 — 이 사고는 2026-09-12에 **이미 한 번 찾았다.** 그때 고친 것은
//      딱 한 곳이었고(index.css 의 그 주석이 남아 있다) 나머지 일곱은 그대로였다.
//      *"잣대가 둘이면 반쪽 적용이 생긴다"* — 이 저장소가 여러 번 데인 자리다.
//      사람이 한 번 더 훑는 것으로는 안 된다. **기계가 세어야 한다.**
//
// ─────────────────────────────────────────────────────────────────────────
// 어떻게 잡나 — 눈으로는 절대 못 잡는 종류다
// ─────────────────────────────────────────────────────────────────────────
//   · 없는 변수를 불러도 **오류가 안 난다.** 빌드도 통과하고 화면도 안 깨진다.
//   · 예비값(`var(--x, #ccc)`)이 있으면 **그럴듯한 색이 나와서** 더 안 보인다.
//     밝은 화면에서 멀쩡해 보이므로, 어두운 화면을 켜 보기 전엔 아무도 모른다.
//   그래서 **쓰는 이름과 정해 둔 이름을 맞대어 센다.** 찍는 게 아니라 재는 것이다.
//
//   npm run check-css-vars

import { readFileSync, readdirSync, statSync } from "node:fs";
import { join } from "node:path";

/** 이 폴더들 밑의 .css 를 다 본다. */
const ROOTS = ["src"];

/**
 * 🚫 우리가 정하지 않아도 되는 이름들 — 브라우저·라이브러리가 주는 것.
 *    늘어나면 여기에 적는다. **적을 때는 이유도 같이 적는다.**
 */
const 남의것 = [
  /^--tw-/, // Tailwind 가 쓰는 이름(혹시 섞여 들어올 때를 대비)
  // 🧩 **코드가 style 로 직접 넣는 이름들.** CSS 파일에는 정의가 없는 게 맞다 —
  //    React 가 `style={{ "--cc": … }}` 로 그때그때 값을 꽂는다.
  //    ⚠️ 여기 적는 순간 검사에서 빠지므로, **진짜 그런지 확인하고 적는다.**
  //       확인하는 법: `grep -rho '"--[a-z-]*"' src/**/*.tsx`
  /^--cc$/, // 갈래 색 — 장소 카드가 갈래에 따라 꽂는다
  /^--offset$/, // 육각 지도 칸이 자기 자리를 꽂는다
  /^--font-lang$/, // 손님이 고른 말의 글꼴 — src/lib/langFont.ts
];

function css파일들(dir) {
  const out = [];
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) out.push(...css파일들(p));
    else if (name.endsWith(".css")) out.push(p);
  }
  return out;
}

const 파일 = ROOTS.flatMap((r) => css파일들(r));

/** 정해 둔 이름 — `--이름:` 꼴로 **값을 준** 자리만 센다. */
const 정한것 = new Set();
/** 부른 이름 — `var(--이름` 꼴. 어느 파일 몇 줄인지 같이 들고 있는다. */
const 부른것 = new Map();

for (const f of 파일) {
  // 🗒️ **주석은 세지 않는다.** 이 저장소는 주석에 「`var(--muted)` 라고 적혀 있었다」
  //    같은 설명을 남긴다 — 그게 잡히면 고칠 것이 없는데 빨간불이 켜진다.
  //    줄 번호는 살려야 하므로 지우지 않고 **같은 길이의 빈칸으로 덮는다.**
  const 원문 = readFileSync(f, "utf8").replace(/\/\*[\s\S]*?\*\//g, (m) => m.replace(/[^\n]/g, " "));
  const 줄들 = 원문.split("\n");
  줄들.forEach((줄, i) => {
    for (const m of 줄.matchAll(/(--[A-Za-z0-9_-]+)\s*:/g)) 정한것.add(m[1]);
    for (const m of 줄.matchAll(/var\(\s*(--[A-Za-z0-9_-]+)/g)) {
      const 이름 = m[1];
      if (!부른것.has(이름)) 부른것.set(이름, []);
      부른것.get(이름).push(`${f}:${i + 1}`);
    }
  });
}

console.log(`🎨 CSS 파일 ${파일.length}개 · 정해 둔 이름 ${정한것.size}개 · 부른 이름 ${부른것.size}개\n`);

const 없는것 = [...부른것.entries()].filter(
  ([이름]) => !정한것.has(이름) && !남의것.some((re) => re.test(이름)),
);

if (!없는것.length) {
  console.log("✅ 없는 변수를 부르는 곳이 없다.");
  process.exit(0);
}

console.error("❌ **정해 둔 적 없는 이름을 부르고 있다.**\n");
for (const [이름, 자리] of 없는것) {
  console.error(`   ${이름}  — ${자리.length}곳`);
  for (const c of 자리) console.error(`      ${c}`);
}
console.error(
  "\n   🚨 이건 오류가 안 나고 화면도 안 깨져서 **눈으로는 못 잡는다.**\n" +
    "      예비값이 붙어 있으면 밝은 화면에서는 그럴듯해 보이고,\n" +
    "      어두운 화면에서만 검정 위의 검정이 된다 (2026-09-15에 실제로 그랬다).\n" +
    "      이름을 오타 냈는지, 아니면 tokens.css 에 정해 주는 것을 잊었는지 볼 것.",
);
process.exit(1);
