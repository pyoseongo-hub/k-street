// 📷 사진 주소를 https로 올린다. 받아 적을 때 **한 번만** 통과시킨다.
//
// 왜 필요한가 (2026-09-04 출시 전 검수에서 찾았다) —
// 관광공사 API는 사진 주소를 **http:// 로** 준다. 그런데 앱은 https:// 로
// 서비스된다(GitHub Pages). https 페이지 안에서 http 사진을 부르면 브라우저가
// 이를 **혼합 콘텐츠**로 보고 막거나 https로 자동 승격한다 — 크롬·파이어폭스는
// 조용히 승격하고 실패하면 그냥 안 보여 주고, 사파리는 아예 막는다.
// **오류 메시지도 안 뜬다. 사진 자리가 그냥 비어 있을 뿐이다.**
//
// 개발할 때는 http://localhost 라서 멀쩡히 보인다 — 그래서 여태 못 봤다.
//
// 다행히 관광공사 사진 서버는 https도 받는다(검사 결과 517개 중 503개 열림.
// 못 연 14개는 애초에 없는 썸네일 404이거나 그때 잠깐 끊긴 것이었다).
// 그래서 **주소만 바꿔 주면 된다.**
//
// 🚨 자료를 받는 스크립트마다 이 함수를 통과시킨다. 한 군데라도 빠뜨리면
//    다음 자동 실행이 http 주소를 다시 채워 넣는다 — 그때는 아무도 모른다.
//    감사(audit-seed의 ❌B11)가 마지막 그물이다.

/** 사진 주소 한 개. 값이 없으면 그대로 돌려준다(빈 칸을 만들어 내지 않는다). */
export function httpsPhoto(url) {
  if (typeof url !== "string") return url;
  return url.startsWith("http://") ? "https://" + url.slice(7) : url;
}
