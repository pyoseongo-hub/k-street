/**
 * 🚮 **코드로는 못 거르는 것** — 이름으로 뺀다.
 *    관광공사에 「주식회사감천아울」·「주식회사뷰티홀릭」처럼 **상호가 그대로 등재된 것**이
 *    섞여 있다. 코드는 제각각이라(A02030400·A02020500·A04011200) 코드로는 못 묶인다.
 */
export const NAME_SKIP = /주식회사|㈜/;

/**
 * 코드가 헷갈릴 때만 쓰는 **이름 규칙**. 짧게 둔다 — 이름 규칙은 도시가 바뀌면 틀어진다.
 * 부산 자료에서 코드로 못 가른 25곳을 눈으로 보고, **확실한 것만** 적었다.
 */
export function defaultNameRule(name) {
  // 🏞️ **국립·도립·군립공원은 코드로 못 가른다** (2026-09-28, 대구·제주 자료).
  //    팔공산국립공원(동화사지구) 과 서귀포해양도립공원이 **같은 코드**(A01010200
  //    「도립공원」)로 온다. 비슬산군립공원은 A01010300 이다. 코드에 어느 쪽을 적어도
  //    한쪽이 틀린다 — **이름이 답을 갖고 있다.**
  //    이걸 안 고치면 대구 등산로가 **0곳**이 된다. 팔공산·비슬산이 자료에 있는데도.
  //    ⚠️ 경주국립공원처럼 산이 아닌 국립공원도 있다. 그 도시를 넣을 때 다시 본다.
  if (/(국립|도립|군립)공원/.test(name))
    return /해양|해상|해안/.test(name) ? "beach" : "hike";
  if (/어촌/.test(name)) return "beach";                       // 공수·대항 어촌체험마을
  if (/(거리|골목)$/.test(name)) return "street";               // 해운대 로데오거리 · 국제시장 먹자골목
  if (/(기찻길|산책로|숲길|둘레길)$/.test(name)) return "walk";  // 청사포 기찻길
  return null;
}

/**
 * 🌊 **바다 갈래** — 바다가 없는 도시에서는 통째로 막는다.
 *
 * 화면에 뜨는 이름이 「바다·해변」이라, 바다가 없는 도시에 하나라도 들어가면
 * 그 자체로 거짓말이 된다. 코드를 아무리 잘 골라도 이건 코드로 못 막는다 —
 * 서울 자료에 **뚝섬 윈드서핑장**(서핑 코드)과 **한강레져스포츠**(수상레포츠 코드)가
 * 실제로 있었다. 한강이지 바다가 아니다.
 *
 * 그래서 **도시 명부(cities.ts)의 `coast` 로 막는다.** 도시마다 규칙을 따로 쓰지 않고
 * 명부 한 칸으로 가른다 — 도시가 늘어도 이 파일은 안 고친다.
 */
export const BEACH_CATEGORY = "beach";

/**
 * 한 곳의 갈래를 정한다.
 *
 * @param {object} item 관광공사 항목
 * @param {{nameRule?: (name: string) => string|null, coast?: boolean}} [opt]
 *   coast — 이 도시에 바다가 있나. **적지 않으면 있다고 친다**(지금까지 하던 대로).
 *   바다가 없다고 적으면 바다 갈래는 null 이 된다 — 다른 칸에 억지로 옮기지 않는다.
 * @returns {{category: string|null, why: string}}
 *   category 가 null 이면 **아직 모르는 것**이다. 억지로 한 칸에 넣지 않는다 —
 *   빈 칸이 틀린 칸보다 낫다(CLAUDE.md 정확도 원칙).
 */
export function categoryOf(item, { nameRule, coast = true } = {}) {
  const code = item.cat3 ?? "";
  const title = String(item.title ?? "");
  if (NAME_SKIP.test(title)) return { category: null, why: "제외(상호)" };
  const skip = SKIP_CODES.get(code);
  if (skip) return { category: null, why: `제외(${skip})` };
  // 축제는 콘텐츠 종류(15)로 이미 갈라져 온다 — 코드보다 이쪽이 확실하다.
  if (String(item.contenttypeid) === "15" || item.__type === "축제공연행사")
    return { category: "festival", why: "관광공사 축제공연행사" };
  const byCode = CODE_TO_CATEGORY.get(code);
  if (byCode) return landlockedGate(byCode, `코드 ${code}`, coast);
  const byName = (nameRule ?? defaultNameRule)(title);
  if (byName) return landlockedGate(byName, `이름 규칙(${byName})`, coast);
  // ⬜ 이름도 답을 안 주면, 그 코드가 **아예 담을 칸이 없는 종류**인지 본다.
  //    「모름(표에서 빠졌다)」과 「담을 칸이 없다」를 가른다 — 위 NO_SLOT_CODES 주석 참고.
  const noSlot = NO_SLOT_CODES.get(code);
  if (noSlot) return { category: null, why: `제외(${noSlot} — 우리 갈래에 없다)` };
  return { category: null, why: `모름 (코드 ${code || "없음"})` };
}

/** 바다가 없는 도시에서 바다 갈래가 나오면 버린다. 다른 칸으로 옮기지 않는다. */
function landlockedGate(category, why, coast) {
  if (category === BEACH_CATEGORY && !coast)
    return { category: null, why: `제외(바다 없는 도시 — ${why})` };
  return { category, why };
}
