/**
 * 후보 파일(src/data/luggage-candidates.json)의 한 줄.
 *
 * ⚠️ 이 모양은 **카카오가 주는 것**이지 우리가 정한 게 아니다.
 *    scripts/survey-luggage-data.mjs 가 받아서 그대로 적는다.
 *    카카오가 칸 이름을 바꾸면 여기도 바뀌어야 한다.
 */
export interface LuggageCandidate {
  /** 어느 역 둘레에서 찾았나 (예: "홍대입구역") */
  area: string;
  id: string;
  name: string;
  /** 카카오 업종. ⚠️ 이걸로는 여행자용/월세 창고가 안 갈린다 — 둘 다 「보관,저장」 */
  category: string;
  jibun: string;
  road: string;
  phone: string;
  /** 역에서 걸어가는 거리(m) */
  distance: number;
  x: string;
  y: string;
  /** 카카오 상세 페이지 */
  url: string;
}
