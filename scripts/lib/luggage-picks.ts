//                                     맡기는 곳인지 확인이 안 됐다
//    · 아트래블 명동서울호스텔          호스텔이다. 묵는 손님 짐만 받을 수 있다
//    · 미미 (명동)                     업종은 무인보관함인데 뭘 하는 곳인지 모르겠다
//    · 스토르 서울역점                  확인이 안 됐다
//    · 빅박스 (경복궁)                  확인이 안 됐다. 전화번호도 없다
//
//    ⚠️ **강남과 경복궁은 통째로 빠졌다.** 강남에서 나온 다섯 곳이 전부 위에
//       해당해서, 자신 있게 올릴 수 있는 게 하나도 없었다. 없는 것을 있다고
//       하느니 그 동네를 안 보여 주는 편이 낫다. 나중에 확인되면 넣는다.
//
// ⚠️ **여기 있는 12곳도 우리가 가 본 곳이 아니다.** 카카오 지도에 그렇게
//    올라와 있다는 것까지가 우리가 아는 전부다. 화면에 그렇게 적는다.

/** 동네 하나 — 역과 그 둘레에서 고른 곳들. */
export interface LuggageArea {
  /** 화면에 그대로 띄우는 한국어 역 이름. 손님이 택시에서 보여 줄 수 있다. */
  ko: string;
  /** 한국어를 못 읽는 손님이 볼 이름. 뒤에 한국어를 괄호로 붙인다. */
  en: string;
  /** 후보 파일(luggage-candidates.json)의 area 값과 **정확히** 같아야 한다. */
  areaKey: string;
  /** 후보 파일의 name 과 **정확히** 같아야 한다. 가까운 순. */
  names: string[];
}

