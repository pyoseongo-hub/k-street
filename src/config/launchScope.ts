// Kfood가 "적은 비용으로 오래"·"수익화보다 커버리지"를 원칙으로 삼은 것과 같은 논리다 —
// 서울 하나를 제대로 채우지 않은 채 전국으로 벌리지 않는다.
//
// 지금은 seed.ts 자체가 서울 25개 구만 갖고 있어서 이 상수가 없어도 결과는 같다.
// 다만 나중에 다른 도시 데이터를 seed.ts에 추가하더라도, **이 상수를 지역·서울 이외로
// 넓히기 전까지는 화면에 노출되지 않아야 한다** — 그래서 지금부터 명시적인 게이트로 둔다.
// 🌊 **부산을 열었다** (2026-09-17, 사장님 결정: *"90퍼 이상이면 열자고"*).
//    사진이 붙은 곳이 202곳 중 184곳(91%)이 된 것을 보고 정하셨다.
//    ⏳ 축제는 아직 14곳뿐이다(관광공사에 그것밖에 없다 — 직접 물어서 확인했다).
//       부산시 자료가 열리면 채운다. 그때까지 부산 화면에 축제는 적게 뜬다.
// 🏙️ **일곱 곳을 더 열었다** (2026-10-01, 사장님 지시:
//    *"제주 광주 대구 경주 대전 전주 강원도 순으로 만들어 … 동네부터 채워서 열고"*).
//    ⏳ 축제는 아직 안 채웠다 — 관광공사 날짜가 2025년에 멈춰 있다.
//       그래서 첫 화면을 동네로 열어 뒀다(HomeSwitch.tsx).
//    🏯 **경주는 경북, 전주는 전북** 안에 있다 — 둘 다 광역시가 아니다.
// 🗺️ **남은 일곱을 열었다** (2026-10-05, 사장님: *"스트릿 비워진 지역 채워"*).
//    인천 163 · 울산 83 · 세종 11 · 경기 869 · 충북 458 · 경남 642 · 전남 611.
//    이것으로 **빈 칸이 있던 시·도가 사라진다**(충남까지 여덟이다).
//    ⚠️ 세종은 11곳뿐이다 — 관광공사 조사 자체가 26줄이다. 빈 칸 5개가 보인다.
//       **감추지 않는다**: 칸이 없으면 빈 곳이 안 보이고, 안 보이면 안 채워진다.
export const LAUNCH_REGIONS: readonly string[] = [
  "서울", "부산",
  "제주", "광주", "대구", "대전", "경북", "전북", "강원",
  "인천", "울산", "세종", "경기", "충북", "경남", "전남", "충남",
];

export function isInLaunchScope(sido: string): boolean {
  return LAUNCH_REGIONS.includes(sido);
}
