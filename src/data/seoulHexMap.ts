// 언론사들이 선거 개표 결과 등에 흔히 쓰는 "서울 25개구 육각형 지도" 템플릿과
// 같은 구 배치를 쓴다(2026-08-28 사용자가 참고 이미지로 제시) — 정치色 있는
// 원본 콘텐츠(득표율·후보 사진)는 가져오지 않고, 구가 어느 행에 어떤 순서로
// 놓이는지 그 배치 구조만 옮겨 온다. districts.ts의 SEOUL_DISTRICTS와 원소가
// 정확히 같아야 한다(개수·이름 불일치는 렌더링 시 빠뜨림으로 이어진다).
//
// offset은 그 행이 왼쪽에서 몇 hex 폭만큼 들여쓰는지다(가장 왼쪽으로 튀어나온
// 4행 = 0 기준). 아래 값은 눈대중이 아니라 참고 이미지를 픽셀 단위로 실측해
// 얻었다(2026-08-28) — 육각형 폭 183.2px, 행별 최좌단 x를 그 폭으로 나눈 값이
// 2.53 / 1.01 / 0.50 / 0.00 / 0.51 / 2.02 로 나와 반 칸 단위에 정확히 떨어졌다.
//
// ⚠️ 육각형은 "위아래가 뾰족하고 좌우가 평평한" 모양이다(참고 이미지 실측:
// 좌변 x가 90px 구간 동안 고정 = 수직변, 상단은 폭이 0에서 늘어남 = 꼭짓점).
// 이 방향이라야 한 행 안에서 수직변끼리 딱 붙고, 행끼리 반 칸 어긋나며 맞물린다.
// 좌우가 뾰족한 모양으로 그리면 가로 이웃이 점으로만 닿아 마름모 구멍이 생긴다
// (실제로 그렇게 만들었다가 어긋나 보인다는 지적을 받았다).
