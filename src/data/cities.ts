//   개수와 정확히 맞았고, 안 맞은 세종은 **시·군·구가 없는 게 맞다**(읍·면 직할).
//   · 대구 군위군은 2023년에 경북에서 넘어왔다 — 대구 9곳 / 경북 22곳으로 반영돼 있다.
//
//   ⚠️ **기계가 만든 것은 아래 `units` 배열뿐이다.** 나머지(주석·타입·함수)는 손으로 썼다.
//      다시 뽑을 일이 있으면 배열만 갈아 끼운다 — 통째로 덮어쓰면 아래 함수가 날아간다.
//
//   lat/lng 는 **시청·도청 자리**다. 날씨(weather.ts)처럼 도시 단위로 충분한 곳에만 쓴다.
//
// ⚠️ **row/col 은 실측 지도가 아니다.** 위도(북→남)·경도(서→동) 순서대로 손으로
//    앉힌 배치다. 서울 육각형 지도(seoulHexMap.ts)는 참고 이미지를 픽셀로 재서
//    만들었지만 이건 그렇지 않다 — 고칠 일이 있으면 위 좌표를 보고 다시 앉히면 된다.

/** 특별시·광역시·특별자치시는 「대도시」, 나머지는 「도」. 사장님 지시대로 갈라 둔다. */
export type CityKind = "대도시" | "도";

/**
 * 지금 이 곳이 앱에서 어떤 상태인가.
 * · 공개   — 자료가 있고 화면에 나온다
 * · 준비중 — 채우는 중이다. 카드에는 보이되 눌러도 아직 방이 없다
 * · 빈칸   — 아직 손도 안 댔다. **보이기는 해야 한다**(안 보이면 안 채운다)
 */
export type CityStatus = "공개" | "준비중" | "빈칸";

export interface City {
  /** 주소에 쓰는 열쇠. korea-street.com/「seoul」/… 의 그 자리다. 바꾸면 주소가 깨진다. */
  key: string;
  /** 짧은 한글 이름 — 화면에 쓴다 */
  ko: string;
  /** 정식 한글 이름 — 공식 자료와 맞춰 볼 때 쓴다 */
  koFull: string;
  /** 짧은 영문 이름 — 카드·칩에 쓴다 */
  en: string;
  /** 정식 영문 이름 — 관광공사 표기 */
  enFull: string;
  kind: CityKind;
  status: CityStatus;
  /** 시청·도청 좌표(날씨용) */
  lat: number;
  lng: number;
  /** 지도식 배치 자리 — 0행이 가장 북쪽, 0열이 가장 서쪽 */
  row: number;
  col: number;
  /** 대도시면 구·군, 도면 시·군. 세종은 읍·면 직할이라 빈 배열이다. */
  units: readonly string[];
}

