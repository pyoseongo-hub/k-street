//   빈 곳이 안 보이고, 안 보이면 영영 안 채워진다. 그래서 자료가 0곳이어도
//   **칸부터 만든다** — status 가 「빈칸」인 곳이 그것이다.
//
// ── 자료 출처 ─────────────────────────────────────────────────────────
//   시·군·구 목록은 **행정표준코드관리시스템 법정동 자료**에서 그대로 뽑았다
