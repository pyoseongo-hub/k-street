export const CITY_BY_KEY: ReadonlyMap<string, City> =
  new Map(CITIES.map((c) => [c.key, c]));

/** 지도식 배치를 그리는 쪽이 쓴다 — 행 개수·열 개수. */
export const MAP_ROWS = 6;
export const MAP_COLS = 5;

/** 지금 자료가 있어 눌러 들어갈 수 있는 곳. */
export const OPEN_CITIES: readonly City[] = CITIES.filter((c) => c.status === "공개");

/**
 * 구·군 이름으로 시·도를 찾는다.
 *
 * 🚨 **「중구」는 여섯 곳에 있다** — 서울·부산·대구·인천·대전·울산.
 *    「서구」·「동구」·「남구」·「북구」·「강서구」도 마찬가지다. 그래서 이름만으로는
 *    못 가른다. 지금은 **공개된 도시가 서울 하나뿐이라** 안 겹칠 뿐이다.
 *
 *    부산을 공개로 바꾸는 순간 「중구」가 겹친다. 그때는 자료(Place)에 city 를
 *    적어서 넘겨야 한다 — 안 적으면 **부산 중구 자료가 서울로 새어 들어온다.**
 *    그 사고를 막으려고 아래가 겹칠 때 city 없이 부르면 빈 값을 돌려준다.
 */
export function sidoOf(gu: string, city?: string): string {
  if (city) {
    const c = CITY_BY_KEY.get(city);
    if (!c) return "미확인";
    // 🚨 도시를 알려 줬다고 그대로 믿지 않는다. **그 구가 그 도시 것인지** 본다.
    //    이 확인을 빼면 게이트가 아무것도 안 거르는 빈 껍데기가 된다
    //    (2026-09-16에 실제로 그렇게 썼다가 되돌렸다 — 서울 목록에 없는 구까지
    //     전부 통과하고 있었다).
    //    세종만 예외다 — 시·군·구 단계가 없어서 units 가 비어 있다.
    if (!c.units.length || c.units.includes(gu)) return c.ko;
    return "미확인";
  }
  const hits = OPEN_CITIES.filter((c) => c.units.includes(gu));
  if (hits.length === 1) return hits[0].ko;
  if (hits.length > 1) {
    // 겹쳤는데 어느 도시인지 안 알려 줬다. 찍지 않는다 — 찍으면 조용히 틀린다.
    if (import.meta.env?.DEV) {
      console.warn(`[cities] 「${gu}」는 ${hits.map((c) => c.ko).join("·")}에 다 있다.`
        + " Place.city 를 적어야 한다.");
    }
    return "미확인";
  }
  return "미확인";
}

