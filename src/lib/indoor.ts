// 🌧️ **비를 안 맞고 둘러볼 수 있는 곳** — 「비 오는 날」 테마의 잣대.
//
// 사장님 지시 (2026-09-12):
//   "비오는날은 우리 것과 거리가 있지만 다르게 생각해보면 관광객에게 정말
//    필요한 것일 수도 있어. 쇼핑 우리와 관계없지만 관광객 입장에선 쇼핑도
//    그 일부이니, 비오는날 쇼핑이나 실내시장 이런쪽 안내가 있으면
//    아주 좋아할 거야. 한쪽 테마로 만들어두자."
//
// ─────────────────────────────────────────────────────────────────────────
// 🔎 이 잣대는 **조사해서 나온 것**이다 (docs/AI검색-최적화.md §비 오는 날)
// ─────────────────────────────────────────────────────────────────────────
//   사장님이 주신 「비 오는 날 서울」 글 6개를 읽었다. 뼈대가 셋 다 달랐는데
//   (9호선 노선 축 / 지하로 다 연결 / 역에서 도보 3분) **이 점에서만 같았다** —
//
//     장소가 실내인 것보다 **거기까지 가는 길이 안 젖는 것**이 핵심이다.
//
//   그래서 잣대를 둘로 잡았다. **둘 다 우리가 이미 아는 사실**이라
//   지어낼 자리가 없다:
//     ① 실내다        — 갈래로 알거나, 확인해서 적어 둔 것
//     ② 역에서 가깝다 — 미터로 안다 (nearest-station.json)
//
// ⚠️ 그 글들 중 **AI 가 만진 3개는 전부 사실이 틀렸다.**
//    「모든 명소 무료」(유료인 곳이 섞였다) · 「우산 없이 진입」(축구장을 지나야 한다)
//    · 영업시간이 6곳 전부 「확인 필요」. 우리가 이기는 길은 더 많이 쓰는 게 아니라
//    **확인한 것만 쓰는 것**이다. 그래서 이 파일은 **모르면 빼는 쪽**으로 판단한다.

import type { Place } from "../data/seed";

/**
 * 갈래만으로 **실내라고 단정할 수 있는** 것.
 *
 * 박물관·미술관은 정의상 건물 안이다. 나머지 갈래는 아니다 —
 * 시장은 아케이드일 수도 노천일 수도 있고, 거리·산책길·등산로는 바깥이고,
 * 축제는 해마다 자리가 바뀐다(2026년 빛섬축제가 뚝섬에서 노들섬으로 옮겼다).
 *
 * 🏬 **shop(상가·몰·아울렛)은 넣는다** (2026-09-12). 「상가(商街)」·「몰」·「아울렛」은
 *    **건물**이다 — 박물관과 같은 수준으로 확실하다. 사장님 지시로 들인 갈래이기도 하다:
 *    "실내식물원이나 전시장, 대형 쇼핑몰도 연결해. 그래야 다양성 확보".
 *
 * 🚨 **여기에 market 을 넣고 싶어질 것이다. 넣으면 안 된다.**
 *    광장시장·남대문시장에 지붕이 있다는 건 널리 알려진 말이지만
 *    **우리가 확인한 사실이 아니고**, 68곳 전부가 그런 것도 아니다.
 *    확인한 시장은 seed 의 `indoor: true` 로 하나씩 올린다.
 */
const INDOOR_CATEGORIES = new Set(["museum", "shop"]);

/**
 * 🚫 **갈래는 박물관인데 실제로는 야외인 곳.**
 *
 * 관광공사에서 받아 온 곳은 seed 에 직접 `indoor: false` 를 적을 자리가 없어서
 * (자료 파일에서 만들어진다) 이름으로 뺀다.
 *
 * 🐞 처음 만들어 보니 **「국립중앙박물관 전통염료식물원」이 53곳 안에 있었다.**
 *    식물원은 야외다 — 비 오는 날 가라고 안내하면 그게 곧 틀린 정보다.
 *    갈래(museum)만 믿으면 이런 것이 새어 든다. 그래서 이 목록이 있다.
 *
 * ⚠️ **NFC 로 맞춰서 본다.** 자모가 분해된 글자(NFD)는 화면에 똑같이 보여도
 *    다른 문자열이라 그냥 비교하면 안 걸린다(이 저장소가 유튜브 제목에서 당했다).
 */
const NOT_INDOOR = new Set(["국립중앙박물관 전통염료식물원"].map((n) => n.normalize("NFC")));

/**
 * 🏪 **중앙 통로에 지붕이 있는 시장** (2026-09-12).
 *
 * 사장님이 우리 시장 68곳 목록을 받아 **직접 하나씩 보고** 골라 주셨다.
 * 그리고 함께 짚어 주신 말이 이 칸의 성격을 정한다:
 *
 *   > **"전체 아케이드 아닌 중앙통로 기준 아케이드 시장이야. 안내문구"**
 *
 * 🚨 그래서 이건 「실내」와 **다른 것**이다. 박물관은 문을 닫으면 비가 한 방울도
 *    안 들지만, 이 시장들은 **중앙 통로만** 덮여 있고 **안쪽 골목은 하늘이 열려
 *    있을 수 있다.** 그 사실을 화면에 같이 적지 않으면 손님이 안쪽에서 젖는다
 *    (page-strings 의 `rainyArcadeNote`). **목록과 안내문구는 한 세트다.**
 *
 * 📌 왜 사람이 골랐나 — 공공자료(ListTraditionalMarket)에 「형태」 칸이 있지만
 *    그 값이 아케이드를 뜻하는지 **아직 확인 못 했다.** 칸 이름만 보고 쓰면 추측이다.
 *    나중에 그 값을 세어 **여기와 대조**한다 — 겹치면 둘 다 더 믿을 수 있다.
 *
 * ⚠️ **NFC 로 맞춰서 본다.** 자모 분해형은 화면에 같아 보여도 다른 문자열이다.
 * ⚠️ 여기 없는 시장은 「지붕이 없다」가 아니라 **「아직 확인 안 했다」**다.
 *    확인 안 한 것을 넣지 않는 쪽으로 틀린다 — 잘못 빼면 손님이 그 시장을 못 보고,
 *    잘못 넣으면 **손님이 비를 맞는다.**
 */
const ARCADE_MARKETS = new Set(
  [
    "숭인시장",
    "송화벽화시장",
    "아현시장",
    "서울 중앙시장",
    "암사종합시장",
    "동대문종합시장 액세서리상가",
    "서울풍물시장",
    "청량리종합시장",
    "광장시장",
    "오류시장",
    "인현시장",
    "상계중앙시장",
    "면목시장",
    "화곡본동시장",
    "망원시장",
    "서울 중부시장",
    "양재꽃시장",
    "중곡제일골목시장",
    "노량진수산물도매시장",
    "구로시장",
    "경동시장",
    "망원월드컵시장",
    "영등포전통시장",
    "남구로시장",
    "공릉동도깨비시장",
    "마장축산물시장",
    "수유시장",
    "노룬산골목시장",
    "독립문영천시장",
  ].map((n) => n.normalize("NFC")),
);

/** 중앙 통로에 지붕이 있는 시장인가. */
export function isArcade(p: Place): boolean {
  return ARCADE_MARKETS.has(p.name.normalize("NFC"));
}

/** 🌧️ 비를 피할 수 있는 곳인가 — 건물 안이거나, 지붕 있는 시장이거나. */
export function isRainOk(p: Place): boolean {
  return isIndoor(p) || isArcade(p);
}

/**
 * 이 곳이 비를 피할 수 있나.
 *
 * 사람이 적어 둔 `indoor` 가 **갈래 판단을 이긴다** — 갈래는 거칠고
 * 사람이 확인한 것은 그 곳 하나에 대한 사실이기 때문이다.
 */
export function isIndoor(p: Place): boolean {
  if (p.indoor != null) return p.indoor;
  if (NOT_INDOOR.has(p.name.normalize("NFC"))) return false;
  return INDOOR_CATEGORIES.has(p.category);
}

/**
 * 「젖는 시간」의 경계 — 지하철역에서 이 거리 안이라야 테마에 들어간다.
 *
 * 🚨 우리 거리는 **직선거리**다. 실제로 걷는 길은 이보다 길다.
 *    그래서 넉넉하게 잡지 않고 **짧게** 잡는다 — 넉넉하게 잡으면
 *    「가깝다고 해서 갔는데 젖었다」가 된다. 그 방향으로는 틀리지 않는다.
 *
 *    600m = 직선으로 약 7분. 실제로는 10분쯤 걸릴 수 있다.
 *
 * 🚨 **아케이드 시장에만 쓴다.** 실내 목적지는 아래 잣대가 따로 있다.
 */
export const ARCADE_WALK_MAX_M = 600;

/**
 * 🏛️ **실내 목적지는 1km까지 본다** (2026-09-12).
 *
 * 왜 잣대가 둘인가 — **손님이 그 곳에서 보내는 시간이 다르기 때문**이다.
 *
 *   · 아케이드 시장은 **지나가며 들르는 곳**이다. 안에 있는 시간이 20분인데
 *     역에서 12분을 걸으면 **젖으러 가는 셈**이 된다. 그래서 600m.
 *   · 박물관·미술관·식물원은 **작정하고 가는 곳**이다. 안에서 두 시간을 보낸다.
 *     10분 걷는 것이 하루를 망치지 않는다. 우산 쓰고 가면 되는 거리다.
 *
 * 📊 **이 줄 하나가 6곳을 들인다** — 600m 로 두면 아래가 전부 빠진다:
 *      647m 포스코미술관(강남) · 657m 경희대학교 자연사박물관(동대문)
 *      790m 화랑대역사 전시관(노원) · 890m 호림박물관 신림본관(관악)
 *      983m 간송미술관(성북) · 984m 국립국악박물관(서초)
 *    강남·동대문·노원·관악·성북·서초 — **다 빈 칸이던 구들**이다.
 *
 * 🚨 **그래도 거리는 줄마다 그대로 적는다.** 「983m 떨어져 있다」를 보여 주고
 *    **손님이 정하게 한다.** 이 잣대가 하는 일은 목록을 **짧게 유지하는 것**이지
 *    「가깝다」고 말해 주는 것이 아니다. 1km 밖 3곳은 여전히 뺀다
 *    (근현대사기념관 1,168m · 목인박물관 1,362m · 상상톡톡 미술관 1,463m).
 */
export const INDOOR_WALK_MAX_M = 1000;

/** 이 안쪽은 「우산 쓰고 3분」이라고 말해도 되는 거리 */
export const RAIN_WALK_NEAR_M = 300;

/** 그 곳이 테마에 들어올 수 있는 최대 거리 — 실내냐 아케이드냐로 갈린다. */
export function rainWalkMax(p: Place): number {
  return isIndoor(p) ? INDOOR_WALK_MAX_M : ARCADE_WALK_MAX_M;
}
