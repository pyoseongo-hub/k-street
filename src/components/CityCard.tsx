import { useLanguage } from "../lib/useLanguage";
import { useCity } from "../lib/useCity";

// 📍 **지금 보는 도시 — 머리줄 그림에서 글자 칸으로 내려왔다.** (2026-10-01)
//
// 사장님이 화면에 동그라미를 쳐서:
//   *"여기 세 칸으로 만들고 위치선택 여기에 넣어. 지금 맨 위고 텍스트도 아니라
//     눈에 안 띄어."*
//
// ── ⏪ 앞판이 왜 안 보였나 ───────────────────────────────────────────────
//   머리줄 오른쪽에 **📍 그림 하나**로 뒀다(2026-09-17). 그때는 그게 맞았다 —
//   화면 맨 아래 카드를 위로 올리는 게 급했고, 이름까지 적으면 360~420px 에서
//   머리줄이 가로로 34px 밀려 나갔다. 그래서 **글자를 빼고 그림만** 남겼다.
//
//   🚨 그런데 그러면서 **고르는 것인지 알 수 없게 됐다.** 📍·✈️·🌙·🔗 가 나란히
//      네 개 서 있으면 손님은 그중 어느 것이 도시 고르개인지 모른다. 그림 하나는
//      「아는 사람에게만 보이는」 단추다. 아홉 도시가 열린 지금은 더 그렇다 —
//      도시를 고르는 일이 이 앱에서 **가장 먼저 하는 일**이 됐다.
//
// ── 그래서 ───────────────────────────────────────────────────────────────
//   영상·날씨가 있는 **글자 칸 줄로 내려오고, 그 줄을 세 칸으로** 만들었다.
//   거기는 글자를 쓰는 자리라 머리줄 폭 싸움(위 앞판 이야기)에서 자유롭다.
//
// 🔑 **큰 글씨는 지금 도시, 작은 글씨가 「위치 선택」이다.** 순서를 뒤집지 말 것 —
//    손님이 먼저 알아야 할 것은 **지금 어디를 보고 있나**이고, 바꿀 수 있다는 것은
//    그다음이다. 날씨 칸이 「24°」를 크게 쓰고 「≈24°」를 작게 쓰는 것과 같은 손이다.
// 🔽 오른쪽 ▾ 는 **아래에서 시트가 올라온다**는 표시다. 영상 칸의 ↗(새 창으로 나간다)와
//    달라야 한다 — 같은 모양을 쓰면 누르기 전에 무슨 일이 날지 알 수 없다.
//
// 🙈 **고를 도시가 하나뿐이면 아예 안 그린다.** 눌러도 아무 일 없는 단추는 손님 눈에
//    「고장 난 앱」이다(CityPicker.tsx 의 오랜 규칙 그대로). 그때는 남은 두 칸이
//    줄 전체를 나눠 쓴다 — index.css 의 flex: 1 이 맡는다.
export default function CityCard({ onOpen }: { onOpen: () => void }) {
  const { t, language } = useLanguage();
  const { city, canChoose } = useCity();
  if (!canChoose) return null;

  // 🌏 도시 **이름**은 translations.ts 에 없다 — 17곳 × 12언어 = 204칸을 손으로 채우면
  //    반드시 어긋난다. 한국어 손님에게는 한글, 나머지 손님에게는 로마자를 준다.
  //    로마자는 안내판·지하철·고속버스표에 실제로 쓰는 표기라 그대로 들고 물어볼 수 있다.
  //    (CityPicker.tsx 가 같은 규칙을 쓴다 — 둘이 갈리면 시트와 칸의 이름이 달라진다.)
  const name = language === "ko" ? city.ko : city.en;

  return (
    <button type="button" className="top-card city-card-top" onClick={onOpen}>
      <span className="top-card-ic" aria-hidden="true">
        📍
      </span>
      <span className="top-card-tx">
        <strong>{name}</strong>
        <span>{t.cityCardLabel}</span>
      </span>
      <span className="top-card-go" aria-hidden="true">
        ▾
      </span>
    </button>
  );
}
